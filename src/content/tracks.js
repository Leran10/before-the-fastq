export const trackById = Object.fromEntries(tracks.map(t => [t.id, t]));

export function stepEntries(track) {
  return track.steps.filter(e => typeof e === 'string' || e.step).map(e => typeof e === 'string' ? { step: e } : e);
}

// Which tracks contain a given step
export function tracksForStep(stepId) {
  return tracks.filter(t => stepEntries(t).some(e => e.step === stepId));
}

